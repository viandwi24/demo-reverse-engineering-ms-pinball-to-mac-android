template <typename T>
void find(TPinballTable* table, const char* name, T*& out) {
    for (TPinballComponent* c : table->component_list)
        if (c->group_name && std::strcmp(c->group_name, name) == 0) {
            out = static_cast<T*>(c);
            return;
        }
    out = nullptr;
}
